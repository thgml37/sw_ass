create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  phone text,
  drink text not null,
  size text not null check (size in ('S', 'M', 'L')),
  options text[] not null default '{}',
  quantity integer not null check (quantity between 1 and 20),
  request text,
  unit_price integer not null check (unit_price >= 0),
  total_price integer not null check (total_price >= 0),
  created_at timestamptz not null default now()
);
alter table public.orders enable row level security;
revoke all on table public.orders from anon, authenticated;
grant insert on table public.orders to anon, authenticated;
grant usage, select on sequence public.orders_id_seq to anon, authenticated;
drop policy if exists "Allow public order submissions" on public.orders;
create policy "Allow public order submissions" on public.orders for insert to anon, authenticated with check (char_length(customer_name) between 1 and 40 and char_length(drink) between 1 and 80 and size in ('S', 'M', 'L') and quantity between 1 and 20 and unit_price >= 0 and total_price >= 0);
